const COVER_TYPES = ['Plastic', 'MagSafe', 'Silicone'];
function coverInventoryRows() {
  return COVER_INVENTORY.filter(row => row.stock > 0 && Number.isInteger(row.stock) && COVER_TYPES.includes(row.type));
}
function coverModels(brand) {
  return [...new Set(coverInventoryRows().filter(row => row.brand === brand).map(row => row.model))].sort((a,b)=>a.localeCompare(b,undefined,{numeric:true}));
}
function coverVariant(row) {
  return {...row, id: 'cover-stock-' + row.id, category: 'covers', title: row.type + ' · ' + row.color};
}
